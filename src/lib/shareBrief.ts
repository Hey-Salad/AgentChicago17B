import type { ResearchBrief } from '../agent'

function slugify(input: string): string {
  return (
    input
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 60) || 'brief'
  )
}

export function briefFileBase(brief: ResearchBrief): string {
  return `agentchicago17b-${slugify(brief.synthesis.title || brief.query)}`
}

export function briefToMarkdown(brief: ResearchBrief): string {
  const s = brief.synthesis
  const lines: string[] = [
    `# ${s.title}`,
    '',
    `> Research question: ${brief.query.split('\n')[0]}`,
    '',
    `Mode: ${brief.mode} · Confidence: ${s.confidence ?? 'n/a'} · ${new Date(brief.createdAt).toLocaleString()}`,
    '',
    '## Executive summary',
    '',
    s.executiveSummary,
    '',
    '## Reframed question',
    '',
    s.reframedQuestion,
    '',
    '## Synthesis',
    '',
    s.narrative,
    '',
    '## Key findings',
    '',
    ...s.keyFindings.map((item) => `- ${item}`),
    '',
    '## Open questions',
    '',
    ...s.openQuestions.map((item) => `- ${item}`),
    '',
    '## Recommended next steps',
    '',
    ...s.recommendedNextSteps.map((item, i) => `${i + 1}. ${item}`),
  ]

  if (brief.sources.length) {
    lines.push('', '## Bibliography', '')
    brief.sources.forEach((source, index) => {
      const n = index + 1
      const bits = [
        `“${source.title}.”`,
        source.publisher || null,
        source.publishedAt || null,
        source.url ? `${source.url}.` : null,
      ].filter(Boolean)
      lines.push(`${n}. ${bits.join(' ')}`)
    })
  }

  lines.push(
    '',
    '---',
    '',
    '_Generated by AgentChicago17B — open source by HeySalad._',
  )
  return lines.join('\n')
}

export function briefToEmailBody(brief: ResearchBrief): string {
  const md = briefToMarkdown(brief)
  // mailto: bodies are limited; keep a useful preview
  const max = 1800
  if (md.length <= max) return md
  return `${md.slice(0, max)}\n\n…\n\n[Brief truncated for email. Use Share → PDF or Download Markdown for the full brief.]`
}

export function briefToPrintableHtml(brief: ResearchBrief): string {
  const s = brief.synthesis
  const findings = s.keyFindings.map((item) => `<li>${escapeHtml(item)}</li>`).join('')
  const questions = s.openQuestions.map((item) => `<li>${escapeHtml(item)}</li>`).join('')
  const next = s.recommendedNextSteps
    .map((item) => `<li>${escapeHtml(item)}</li>`)
    .join('')
  const biblio = brief.sources
    .map((source, index) => {
      const label = [source.title, source.publisher, source.publishedAt, source.url]
        .filter(Boolean)
        .join(' — ')
      return `<li>[${index + 1}] ${escapeHtml(label)}</li>`
    })
    .join('')

  const narrative = s.narrative
    .split(/\n+/)
    .map((p) => `<p>${escapeHtml(p)}</p>`)
    .join('')

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(s.title)} — AgentChicago17B</title>
  <style>
    @page { margin: 18mm; }
    body {
      font-family: Figtree, "Segoe UI", Helvetica, Arial, sans-serif;
      color: #111;
      line-height: 1.45;
      max-width: 720px;
      margin: 0 auto;
      padding: 24px;
    }
    .brand { color: #ed4c4c; font-weight: 800; letter-spacing: -0.02em; }
    .meta { color: #555; font-size: 12px; margin-bottom: 20px; }
    h1 { font-size: 26px; margin: 0 0 8px; letter-spacing: -0.02em; }
    h2 { font-size: 14px; text-transform: uppercase; letter-spacing: 0.06em; color: #ed4c4c; margin: 22px 0 8px; }
    p { margin: 0 0 10px; }
    ul, ol { margin: 0 0 10px; padding-left: 1.2em; }
    .footer { margin-top: 28px; font-size: 11px; color: #777; border-top: 1px solid #ddd; padding-top: 10px; }
    @media print {
      body { padding: 0; }
      .no-print { display: none !important; }
    }
  </style>
</head>
<body>
  <p class="brand">AgentChicago17B · HeySalad</p>
  <h1>${escapeHtml(s.title)}</h1>
  <p class="meta">
    ${escapeHtml(brief.query.split('\n')[0])}<br />
    ${escapeHtml(brief.mode)} mode · ${escapeHtml(s.confidence ?? 'n/a')} confidence ·
    ${escapeHtml(new Date(brief.createdAt).toLocaleString())}
  </p>
  <h2>Executive summary</h2>
  <p>${escapeHtml(s.executiveSummary)}</p>
  <h2>Reframed question</h2>
  <p>${escapeHtml(s.reframedQuestion)}</p>
  <h2>Synthesis</h2>
  ${narrative}
  <h2>Key findings</h2>
  <ul>${findings}</ul>
  <h2>Open questions</h2>
  <ul>${questions}</ul>
  <h2>Recommended next steps</h2>
  <ol>${next}</ol>
  ${biblio ? `<h2>Bibliography</h2><ol>${biblio}</ol>` : ''}
  <p class="footer">One brief. Deep as the dish. — AgentChicago17B (MIT)</p>
  <p class="no-print" style="margin-top:16px">
    <button onclick="window.print()">Save as PDF / Print</button>
  </p>
  <script>window.addEventListener('load', () => setTimeout(() => window.print(), 250));</script>
</body>
</html>`
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function downloadBlob(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export function downloadBriefMarkdown(brief: ResearchBrief) {
  downloadBlob(`${briefFileBase(brief)}.md`, briefToMarkdown(brief), 'text/markdown;charset=utf-8')
}

export function downloadBriefHtml(brief: ResearchBrief) {
  downloadBlob(
    `${briefFileBase(brief)}.html`,
    briefToPrintableHtml(brief).replace(
      /<script>[\s\S]*?<\/script>/,
      '',
    ),
    'text/html;charset=utf-8',
  )
}

/** Opens a print window — choose “Save as PDF” in the system dialog. */
export function shareBriefAsPdf(brief: ResearchBrief) {
  const html = briefToPrintableHtml(brief)
  const win = window.open('', '_blank', 'noopener,noreferrer,width=900,height=1000')
  if (!win) {
    downloadBriefHtml(brief)
    return { ok: false as const, reason: 'popup-blocked' as const }
  }
  win.document.open()
  win.document.write(html)
  win.document.close()
  return { ok: true as const }
}

export function shareBriefByEmail(brief: ResearchBrief, to = '') {
  const subject = encodeURIComponent(`Research brief: ${brief.synthesis.title}`)
  const body = encodeURIComponent(briefToEmailBody(brief))
  const href = `mailto:${encodeURIComponent(to)}?subject=${subject}&body=${body}`
  window.location.href = href
}

export async function copyBriefMarkdown(brief: ResearchBrief): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(briefToMarkdown(brief))
    return true
  } catch {
    return false
  }
}
